const mongoose = require('mongoose');

const templateSchema = new mongoose.Schema({
  // New Meta specific fields
  name:            { type: String, required: true }, // lowercase and underscores only
  category:        { type: String, required: true, enum: ['MARKETING', 'UTILITY', 'AUTHENTICATION'] },
  language:        { type: String, required: true, default: 'en' },
  components:      { type: Array, default: [] }, // Stores the raw Meta components array
  metaTemplateId:  { type: String }, // Returned from Meta after creation
  // Mirrors Meta's own status vocabulary (Meta returns more states than the
  // three we care about, and an unknown value must never block a save).
  metaStatus: {
    type: String,
    enum: [
      'DRAFT',
      'PENDING',
      'IN_REVIEW',
      'APPROVED',
      'REJECTED',
      'PAUSED',
      'DISABLED',
      'FLAGGED',
      'PENDING_DELETION',
      'LIMIT_EXCEEDED',
      'APPEAL_PENDING',
    ],
    default: 'DRAFT',
  },
  wabaId:          { type: String }, // Meta WhatsApp Business Account ID
  // Meta's `source` field. Direct Send auto-generates templates with
  // `source: 'AUTO_GENERATED'`, and Meta forbids editing or deleting those.
  source:          { type: String, default: '' },
  isAutoGenerated: { type: Boolean, default: false },

  // Original fields (kept for legacy/fallback)
  title:           { type: String }, 
  message:         { type: String }, 
  footer:          { type: String, default: '' },
  imageUrl:        { type: String, default: '' },
  mediaId:         { type: String, default: '' }, // Meta Media ID for sending

  // Friendly mirror of `components` so the studio can re-open a template for
  // editing without re-parsing the raw Meta payload.
  header_type:      { type: String, default: 'NONE' },
  header_text:      { type: String, default: '' },
  header_image_url: { type: String, default: '' },
  body_text:        { type: String, default: '' },
  footer_text:      { type: String, default: '' },
  sample_values:    { type: [String], default: [] },
  buttons:          { type: Array, default: [] },
  
  // Stats & Scheduling (unchanged)
  contacts:        [{ type: String }],
  totalSent:       { type: Number, default: 0 },
  totalFailed:     { type: Number, default: 0 },
  interested:      { type: Number, default: 0 },
  notInterested:   { type: Number, default: 0 },
  ordersGenerated: { type: Number, default: 0 },
  status: {
    type: String,
    enum: ['draft', 'sending', 'completed', 'failed', 'scheduled'],
    default: 'draft',
  },
  sentAt:       Date,
  isScheduled:  { type: Boolean, default: false },
  scheduleTime: { type: String, default: '' },     // "HH:MM"
  repeatDaily:  { type: Boolean, default: false },
  scheduleDays: [{ type: String }],                // ['mon','tue',...] empty = every day
  lastRunAt:    { type: Date },
  nextRunAt:    { type: Date },
  isActive:     { type: Boolean, default: true },
}, { timestamps: true });

module.exports = mongoose.model('Template', templateSchema);